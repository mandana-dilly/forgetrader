def _check(failures, cond, msg):
    """Record `msg` in `failures` unless `cond`. Returns 1 on pass, 0 on fail
    so the caller can total an assertion count."""
    if cond:
        return 1
    failures.append(msg)
    return 0


def run_family_a(failures):
    passed = 0
    for label, from_stage, trigger, exp_action, exp_to, legal in FAMILY_A:
        state = _state_at(from_stage)
        new_state, action = fs.apply_trigger(state, trigger)

        passed += _check(
            failures, action == exp_action,
            f"{label}: action expected {exp_action!r} got {action!r}")
        passed += _check(
            failures, new_state["wheel"]["stage"] == exp_to,
            f"{label}: new stage expected {exp_to!r} got "
            f"{new_state['wheel']['stage']!r}")
        passed += _check(
            failures, state["wheel"]["stage"] == from_stage,
            f"{label}: caller stage mutated to "
            f"{state['wheel']['stage']!r} (expected {from_stage!r})")

        if legal:
            passed += _check(
                failures, new_state is not state,
                f"{label}: legal path must deep-copy, "
                f"new_state IS the input object")
        else:
            passed += _check(
                failures, new_state is state,
                f"{label}: illegal path must return the input object, "
                f"got a copy")
    return passed


def run_family_b(failures):
    passed = 0
    for label, stage, snapshot, exp_action, exp_stage, kind in FAMILY_B:
        state = _state_at(stage)
        new_state, action = fs.reconcile(state, snapshot)

        passed += _check(
            failures, action == exp_action,
            f"{label}: action expected {exp_action!r} got {action!r}")
        passed += _check(
            failures, new_state["wheel"]["stage"] == exp_stage,
            f"{label}: resulting stage expected {exp_stage!r} got "
            f"{new_state['wheel']['stage']!r}")
        passed += _check(
            failures, state["wheel"]["stage"] == stage,
            f"{label}: caller stage mutated to "
            f"{state['wheel']['stage']!r} (expected {stage!r})")

        if kind == "transition":
            passed += _check(
                failures, new_state is not state,
                f"{label}: transition must hand back a new state object, "
                f"got the input")
        else:  # noop / halt
            passed += _check(
                failures, new_state is state,
                f"{label}: {kind} must return the input state object, "
                f"got a copy")
    return passed


