# --------------------------------------------------------------------------- #
# Runner                                                                     #
# --------------------------------------------------------------------------- #

def _real_halt_files():
    return set(glob.glob(os.path.join(str(_REAL_SCANS), "state_halt_*.txt")))


SCENARIOS = [scenario_1, scenario_2, scenario_3, scenario_4, scenario_5]


def main(argv):
    failures = []

    # Self-isolation guard: snapshot the real scans dir once, up front.
    real_before = _real_halt_files()

    passed = 0
    for fn in SCENARIOS:
        passed += fn(failures)

    # ... and again at the end. Equal => every write hit the tmp dir.
    real_after = _real_halt_files()
    passed += _check(
        failures, real_before == real_after,
        f"ISOLATION: real scans dir gained/lost state_halt files: "
        f"added {sorted(real_after - real_before)} "
        f"removed {sorted(real_before - real_after)}")

    total_asserts = passed + len(failures)

    if failures:
        print("FAIL")
        for f in failures:
            print("  " + f)
        print(f"{len(SCENARIOS)} scenarios + 1 isolation guard, "
              f"{total_asserts} assertions, {passed} passed, "
              f"{len(failures)} failed")
        return 1

    print(f"PASS: {len(SCENARIOS)} scenarios + 1 isolation guard, "
          f"{total_asserts} assertions")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
