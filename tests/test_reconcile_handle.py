def scenario_4(failures):
    """HALT, conn=None run_id=None: still dumps + alerts, does not crash,
    returns (state, HALT action)."""
    snap = {"shares": 100}
    exc = None
    r = None
    try:
        r = run_scenario("FLAT", snap, use_conn=False, run_id=None)
    except Exception as e:  # noqa: BLE001 - scenario asserts no exception
        exc = e
    p = 0
    p += _check(failures, exc is None,
                f"S4: reconcile_and_handle raised on the None-journal path: {exc!r}")
    if exc is not None:
        return p
    p += _check(failures, len(r["dump_files"]) == 1,
                f"S4: expected exactly 1 dump file, got {len(r['dump_files'])}")
    p += _check(failures,
                r["dump_text"] is not None and S1_REASON in r["dump_text"],
                f"S4: dump text missing reason substring {S1_REASON!r}")
    p += _check(failures, len(r["alert_calls"]) == 1,
                f"S4: expected alert fired once, got {len(r['alert_calls'])}")
    p += _check(failures, r["decisions"] == [],
                f"S4: no journal write should be attempted, got {r['decisions']!r}")
    ret = r["ret"]
    p += _check(failures, isinstance(ret, tuple) and len(ret) == 2,
                f"S4: return value should be a 2-tuple, got {ret!r}")
    if isinstance(ret, tuple) and len(ret) == 2:
        p += _check(failures, ret[1] == S1_HALT_ACTION,
                    f"S4: return action expected {S1_HALT_ACTION!r}, got {ret[1]!r}")
        p += _check(failures, ret[0] is r["state_in"],
                    "S4: return state should be the (unmutated) input state object")
        p += _check(failures, ret[0]["wheel"]["stage"] == "FLAT",
                    f"S4: return state stage expected 'FLAT', "
                    f"got {ret[0]['wheel']['stage']!r}")
    return p


